"""Check the web UI styling rules (ui-design AC-2, AC-11, ADR-0022).

Stdlib only. Usage: ``python infra/scripts/check_web_style.py [ROOT]``. Prints one line
per violation as ``<path under apps/web/src>:<line>: <message>`` (or ``globals.css:
<message>`` for token problems) and exits 1 when any is found.

1. Colours come from tokens: no hex, ``rgb()``-style functions, Tailwind palette classes
   or ``dangerouslySetInnerHTML`` in web sources. Exempt: ``app/globals.css`` (the
   tokens), ``components/ui/`` (generated by the shadcn CLI), ``lib/api/`` (generated)
   and test files.
2. The token pairs in ``globals.css`` are readable in light and dark: text pairs reach
   WCAG AA (4.5:1) and the focus ring reaches 3:1 against the background.
"""

import re
import sys
from collections.abc import Iterator
from pathlib import Path

SOURCE_SUFFIXES = {".ts", ".tsx", ".css"}
EXEMPT_FILES = {"app/globals.css"}
EXEMPT_DIRS = ("components/ui/", "lib/api/")

PALETTE = (
    "red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|"
    "purple|fuchsia|pink|rose|slate|gray|zinc|neutral|stone"
)
LITERALS = [
    (re.compile(r"#[0-9a-fA-F]{3,8}\b"), "colour literal"),
    (
        re.compile(r"\b(?:rgba?|hsla?|oklch|oklab|lab|lch)\("),
        "colour function",
    ),
    (
        re.compile(
            rf"\b(?:bg|text|border|ring|fill|stroke|from|to|via|outline|shadow|"
            rf"divide|decoration|accent|caret)-(?:{PALETTE})-\d{{2,3}}\b"
        ),
        "Tailwind palette class (use a token class)",
    ),
    (re.compile(r"dangerouslySetInnerHTML"), "raw HTML (render text, never HTML)"),
]

# (foreground token, background token, minimum ratio)
TEXT_PAIRS = [
    ("foreground", "background", 4.5),
    ("muted-foreground", "background", 4.5),
    ("card-foreground", "card", 4.5),
    ("primary-foreground", "primary", 4.5),
    ("primary-text", "background", 4.5),
    ("destructive-foreground", "destructive", 4.5),
    ("ring", "background", 3.0),  # focus indicator: non-text contrast
]
THEMES = {"light": ":root", "dark": ".dark"}
COMMENT_STARTS = ("//", "/*", "*")


def is_exempt(rel: str) -> bool:
    name = rel.rsplit("/", 1)[-1]
    return (
        rel in EXEMPT_FILES
        or rel.startswith(EXEMPT_DIRS)
        or ".test." in name
        or ".spec." in name
    )


def sources(src: Path) -> Iterator[tuple[str, Path]]:
    for path in sorted(src.rglob("*")):
        if path.is_file() and path.suffix in SOURCE_SUFFIXES:
            rel = path.relative_to(src).as_posix()
            if not is_exempt(rel):
                yield rel, path


def check_literals(src: Path) -> list[str]:
    problems = []
    for rel, path in sources(src):
        for number, line in enumerate(path.read_text().splitlines(), start=1):
            if line.lstrip().startswith(COMMENT_STARTS):
                continue  # comments may name the forbidden things
            for pattern, label in LITERALS:
                match = pattern.search(line)
                if match:
                    problems.append(f"{rel}:{number}: {label}: {match.group(0)}")
    return problems


def parse_hex(value: str) -> tuple[int, int, int] | None:
    value = value.strip().lstrip("#")
    if len(value) == 3:
        value = "".join(ch * 2 for ch in value)
    if len(value) != 6 or not re.fullmatch(r"[0-9a-fA-F]{6}", value):
        return None
    return int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16)


def luminance(rgb: tuple[int, int, int]) -> float:
    def channel(c: int) -> float:
        s = c / 255
        return s / 12.92 if s <= 0.03928 else ((s + 0.055) / 1.055) ** 2.4

    r, g, b = (channel(c) for c in rgb)
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a: tuple[int, int, int], b: tuple[int, int, int]) -> float:
    hi, lo = sorted((luminance(a), luminance(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def block(css: str, selector: str) -> dict[str, str]:
    """Custom properties declared in the first top-level `<selector> { ... }`."""
    match = re.search(rf"(?m)^{re.escape(selector)}\s*\{{(.*?)^\}}", css, re.S)
    if not match:
        return {}
    return dict(re.findall(r"--([\w-]+)\s*:\s*([^;]+);", match.group(1)))


def check_tokens(css_path: Path) -> list[str]:
    if not css_path.is_file():
        return [f"globals.css: missing: {css_path}"]
    css = css_path.read_text()
    problems = []
    for theme, selector in THEMES.items():
        tokens = block(css, selector)
        if not tokens:
            problems.append(f"globals.css: no `{selector}` block ({theme} theme)")
            continue
        for fg, bg, minimum in TEXT_PAIRS:
            colours = []
            for name in (fg, bg):
                if name not in tokens:
                    problems.append(f"globals.css: {theme}: token --{name} is missing")
                    continue
                rgb = parse_hex(tokens[name])
                if rgb is None:
                    problems.append(
                        f"globals.css: {theme}: --{name} must be #rrggbb, "
                        f"got {tokens[name]!r}"
                    )
                    continue
                colours.append(rgb)
            if len(colours) == 2:
                ratio = contrast(colours[0], colours[1])
                if ratio < minimum:
                    problems.append(
                        f"globals.css: {theme}: --{fg} on --{bg} is {ratio:.2f}:1, "
                        f"needs {minimum}:1"
                    )
    return problems


def main(argv: list[str]) -> int:
    root = Path(argv[1]) if len(argv) > 1 else Path(__file__).resolve().parents[2]
    src = root / "apps" / "web" / "src"
    problems = check_literals(src) + check_tokens(src / "app" / "globals.css")
    problems = list(dict.fromkeys(problems))  # one line per problem
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
